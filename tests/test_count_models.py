@pytest.mark.parametrize("fam", list(cm.FAMILIES))
def test_library_score_in_stata_order_matches_numerical(data, fam):
    """Glue check: statsmodels score mapped to Stata order (count, inflate, ln alpha) = numerical gradient of the LL."""
    spec = cm.FAMILIES[fam]
    d = data.dropna(subset=["만성질환수"])
    if spec["kind"] == "trunc":
        d = d[d["입원일수"].notna()]
        y = d["입원일수"].to_numpy(float)
    else:
        y = d["외래방문"].to_numpy(float)
    X = np.column_stack([d["연령"] / 10, d["여성"], d["만성질환수"], np.ones(len(d))])
    Z = np.column_stack([d["연령"] / 10, np.ones(len(d))])
    lik = cm.CountModel(y, X, np.log(d["관찰개월"].to_numpy(float)), dist=spec["dist"], kind=spec["kind"], Z=Z,
                        link="probit" if fam == "zip" else "logit", trunc=0)
    rng = np.random.default_rng(1)
    t = rng.normal(0, 0.2, lik.k)
    g = lik.score(t)
    num = np.array([(lik.loglike(t + h) - lik.loglike(t - h)) / 2e-6 for h in np.eye(lik.k) * 1e-6])
    close(g, num, rtol=1e-4, atol=1e-3)


def test_sandwich_equals_statsmodels_cov_type(data):
    """vce(robust) = statsmodels HC0 x N/(N-1); vce(cluster) = statsmodels cluster (use_correction=False) x G/(G-1)."""
    import statsmodels.api as sm
    d = data.dropna(subset=["만성질환수"])
    X = np.column_stack([d["연령"], d["여성"], d["만성질환수"], np.ones(len(d))])
    y, off = d["응급실방문"].to_numpy(float), np.log(d["관찰개월"].to_numpy(float))
    g = pd.factorize(d["시군구"])[0]
    n, G = len(y), len(set(g))
    kw = dict(dep="응급실방문", covs=["연령", "여성", "만성질환수"], family="poisson", exposure="관찰개월")
    se_r = coefs(ost.run("countReg", d, covType="robust", **kw))[1]
    se_c = coefs(ost.run("countReg", d, covType="cluster", clusterVar="시군구", **kw))[1]
    m = sm.Poisson(y, X, offset=off)
    close(se_r, m.fit(disp=0, cov_type="HC0").bse * np.sqrt(n / (n - 1)), rtol=1e-6)
    close(se_c, m.fit(disp=0, cov_type="cluster", cov_kwds={"groups": g, "use_correction": False}).bse * np.sqrt(G / (G - 1)),
          rtol=1e-6)


