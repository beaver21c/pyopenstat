@pytest.mark.parametrize("tag,sel,kw", STATA_CASES, ids=[c[0] for c in STATA_CASES])
def test_against_stata(data, hosp, tag, sel, kw):
    S = STATA[tag]
    res = _stata_case(data, hosp, sel, kw)
    e, s = coefs(res)
    close(e, S["b"], rtol=1e-4, atol=1e-5)
    close(s, S["se"], **SE)
    close(stat(res, "로그우도"), S["ll"], **LL)
    assert stat(res, "관측수") == S["N"]
    close(stat(res, "AIC"), S["aic"], **LL)
    close(stat(res, "BIC"), S["bic"], **LL)
    robust = kw.get("covType") in ("robust", "cluster")
    ztp_note = [n for n in res.get_table("summary").notes if n.startswith("Stata tpoisson의 e(ll_0)")]
    if ztp_note:
        # Stata tpoisson: e(ll_0) at the untruncated constant-only estimate; reproduced in a note
        m = re.search(r"\((-?[0-9.]+); 이 값 기준 LR χ² = (-?[0-9.]+)", ztp_note[0])
        close(float(m.group(1)), S["ll_0"], rtol=0, atol=1e-3)
        if robust:
            close(stat(res, "Wald χ²"), S["chi2"], rtol=1e-4)
        else:
            close(float(m.group(2)), S["chi2"], rtol=1e-4)
    else:
        if "ll_0" in S:
            close(stat(res, "상수항"), S["ll_0"], **LL)
        close(stat(res, "Wald χ²" if robust else "LR χ²"), S["chi2"], rtol=1e-4, atol=1e-4)
    if "chi2_c" in S:                                              # nbreg / tnbreg: LR test of alpha (delta) = 0
        close(rows_of(res, "LR 검정")[0]["stat"], S["chi2_c"], rtol=1e-5)
    if "chi2_cp" in S and kw.get("inflateLink") == "logit":       # zinb, zip option (probit: Stata compares a logit zip)
        close(rows_of(res, "LR 검정")[0]["stat"], S["chi2_cp"], rtol=1e-5)
    if "vuong" in S:
        close(rows_of(res, "Vuong")[0]["stat"], S["vuong"], rtol=0, atol=1e-5)
    if "dev" in S:
        close(rows_of(res, "적합도: 이탈도")[0]["stat"], S["dev"], rtol=1e-8)
        close(rows_of(res, "적합도: Pearson")[0]["stat"], S["pearson"], rtol=1e-7)
    if "predprob" in S:
        k = 9 if kw["family"] == "ztp" else 10
        close(predprob(res)[:k], S["predprob"][:k], rtol=0, atol=1e-6)
    if "ame" in S:
        m, ms = ame(res)
        close(m, S["ame"], rtol=1e-4, atol=1e-7)
        close(ms, S["ame_se"], **SE)


@pytest.mark.parametrize("fam,ctag", [("hurdle_poisson", "s_hurdle_tp"), ("hurdle_nb", "s_hurdle_tnb")])
def test_hurdle_against_stata_two_parts(data, fam, ctag):
    """Hurdle = logit for P(y>0) on all obs + zero-truncated count model on y>0 (separable likelihood, Stata in two parts)."""
    C, L = STATA[ctag], STATA["s_hurdle_logit"]
    res = ost.run("countReg", data, family=fam, **ZI_KW)
    e, s = coefs(res)
    close(e, C["b"][:5] + L["b"] + C["b"][5:], rtol=1e-4, atol=1e-6)
    close(s, C["se"][:5] + L["se"] + C["se"][5:], **SE)
    close(stat(res, "로그우도"), C["ll"] + L["ll"], **LL)
    se_r = coefs(ost.run("countReg", data, family=fam, covType="robust", **ZI_KW))[1]
    CR, LR_ = STATA[ctag + "_robust"], STATA["s_hurdle_logit_robust"]
    n_all, n_pos = 1488, int(C["N"])
    adj = np.sqrt((n_pos / (n_pos - 1)) / (n_all / (n_all - 1)))   # joint model: N/(N-1) of all observations
    close(np.concatenate([se_r[:5], se_r[9:]]) * adj, CR["se"], **SE)
    close(se_r[5:9], LR_["se"], **SE)


def test_stata_conventions_chibar2_and_vuong_p(data):
    res = ost.run("countReg", data, family="nb2", **NB_KW)
    lr = rows_of(res, "LR 검정")[0]
    close(lr["p"], 0.5 * stats.chi2.sf(lr["stat"], 1), rtol=1e-12)   # Prob >= chibar2 (0.500 when chibar2 = 0)
    res = ost.run("countReg", data, family="zip", vuong=True, **ZI_KW)
    for r in rows_of(res, "Vuong"):
        close(r["p"], stats.norm.sf(r["stat"]), rtol=1e-12)          # Stata: Pr > z
