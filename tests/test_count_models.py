def test_poisson_vs_glm(data):
    R = REF["s_poisson"]
    res = ost.run("countReg", data, dep="응급실방문", covs=SX, factors=["소득분위"], family="poisson", exposure="관찰개월")
    e, s = coefs(res)
    close(e, R["est"], **EST)
    close(s, R["se"], **SE)
    close(stat(res, "로그우도"), R["ll"], **LL)
    close(stat(res, "상수항"), R["ll0"], **LL)
    close(stat(res, "LR χ²"), 2 * (R["ll"] - R["ll0"]), rtol=1e-6)
    close(rows_of(res, "적합도: 이탈도")[0]["stat"], R["dev"], rtol=1e-8)
    close(rows_of(res, "적합도: Pearson")[0]["stat"], R["pearson"], rtol=1e-7)
    m, ms = ame(res)
    close(m, R["ame"], **EST)
    close(ms, R["ame_se"], **SE)
    close(predprob(res), R["predprob"], rtol=0, atol=1e-7)
    assert res.model_stats["N"] == 1488 and res.model_stats["df"] == 8


