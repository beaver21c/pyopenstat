def coefs(res):
    """Estimates and SEs in Stata order: count equation, inflate / hurdle equation, /lnalpha."""
    est, se = [], []
    for nm in ("coef", "inflate", "hurdle"):
        t = res.get_table(nm)
        if t is not None:
            est += [r["b"] for r in t.rows]
            se += [r["se"] for r in t.rows]
    t = res.get_table("aux")
    if t is not None:
        est.append(t.rows[0]["est"])
        se.append(t.rows[0]["se"])
    return np.array(est), np.array(se)


def stat(res, start):
    return next(r["value"] for r in res.get_table("summary").rows if r["stat"].startswith(start))


def rows_of(res, start):
    return [r for r in res.get_table("tests").rows if r["test"].startswith(start)]


def ame(res):
    t = res.get_table("margins")
    return np.array([r["dydx"] for r in t.rows]), np.array([r["se"] for r in t.rows])


def predprob(res):
    return np.array([r["pred"] for r in res.get_table("predprob").rows])[:10]


def close(a, b, rtol, atol=0.0):
    np.testing.assert_allclose(np.asarray(a, dtype=float), np.asarray(b, dtype=float), rtol=rtol, atol=atol)


