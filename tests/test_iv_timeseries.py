def _panel_data(ds):
    d = pd.read_csv(os.path.join(DATA, "IV_Panel_CareStaff.csv"))
    if ds == "unb":            # trailing years removed (Stata reference run used the same rows)
        keep = pd.read_csv(io.StringIO(UNB_KEEP), header=None).iloc[:, 0].to_numpy()
        return d[(d.year - 2013) <= keep[d.region - 1]].reset_index(drop=True)
    if ds == "gap":            # interior years removed
        return d.drop(index=GAP_DROP).reset_index(drop=True)
    return d


@pytest.mark.parametrize("ds", ["bal", "unb", "gap"])
@pytest.mark.parametrize("m", list(XT_CFG))
def test_panel_iv_matches_stata_xtivreg(ds, m):
    res = PanelIV(_panel_data(ds), dict(XTBASE, **XT_CFG[m]))
    ref = STATA["xt"][f"{ds}_{m}"]
    for nm, (b, se) in _coefs(res, "xtivCoef").items():
        key = nm if m not in ("fd", "fdr") or nm == "_cons" else "D." + nm
        _close(b, ref[f"b:{key}"], 1e-6, 1e-9, f"{ds}_{m} b[{nm}]")
        _close(se, ref[f"se:{key}"], 1e-6, 1e-9, f"{ds}_{m} se[{nm}]")
    fit = _fit(res, "xtivModelFit")
    for lab, key in XT_STATS.items():
        if lab not in fit or key not in ref:
            continue
        if (m == "fdr" and key == "sigma_e") or (ds == "gap" and m in ("fd", "fdr") and key == "r2_w"):
            continue           # documented differences (Stata fd robust e(sigma_e) uses G−1; gap-panel fd within R²)
        if lab == "F" and m != "fes":
            continue
        _close(fit[lab], ref[key], 1e-6, 1e-9, f"{ds}_{m} {key}")


# ---------------------------------------------------------------- arima
def _ts_coefs(res):
    out = {}
    for r in res.get_table("arimaCoef").rows:
        if r["term"] == "/sigma":
            nm = "sigma:_cons"
        elif r["eq"].startswith("ARMA"):
            kind, lag = r["term"].split()[0], r["term"].split()[1].rstrip(".")
            nm = f"{r['eq']}:L.{kind}" if lag == "L1" else f"{r['eq']}:L{lag[1:]}.{kind}"
        else:
            nm = f"{r['eq']}:{r['term']}"
        out[nm] = (r["b"], r["se"])
    return out


