@pytest.mark.parametrize("tag", list(IV_CFG))
def test_ivreg_coefficients_and_fit_match_stata(school, tag):
    res = IVRegression(school, dict(IVBASE, **IV_CFG[tag]))
    ref = STATA["iv"][tag]
    for nm, (b, se) in _coefs(res, "ivCoef").items():
        _close(b, ref[f"b:{nm}"], 1e-6, 1e-9, f"{tag} b[{nm}]")
        _close(se, ref[f"se:{nm}"], 1e-6, 1e-9, f"{tag} se[{nm}]")
