def _close(ours, ref, rel=1e-6, abs_=1e-9, what=""):
    assert ref is not None and np.isfinite(ref), f"missing reference {what}"
    assert abs(ours - ref) <= max(abs_, rel * abs(ref)), f"{what}: ours {ours!r} vs Stata {ref!r}"


def _coefs(res, table):
    return {("_cons" if r["term"] == "Intercept" else r["term"].replace("D.", "")): (r["b"], r["se"]) for r in res.get_table(table).rows}


def _tests(res, name):
    t = res.get_table(name)
    return {r["test"]: r for r in t.rows} if t else {}


def _fit(res, table="ivModelFit"):
    return {r["stat"]: r["value"] for r in res.get_table(table).rows}


