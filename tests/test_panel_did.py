# ----------------------------------------------------------------------------- wild cluster bootstrap
def _wb_inputs(df, group):
    D = DiDData(df, "region", "year", "y1", ["x1"], [], "treat1", group, None)
    Td, _ = D.time_dummies()
    Z = np.column_stack([D.P.df[["x1"]].to_numpy(float), Td])
    Zt, dt, yt = (_within_matrix(a, D.g, D.n) for a in (Z, D.d, D.y))
    coef = np.linalg.lstsq(Zt, np.column_stack([yt, dt]), rcond=None)[0]
    cl = pd.factorize(D.P.df[group])[0] if group != "region" else D.g
    return D, Z, Zt, yt - Zt @ coef[:, 0], dt - Zt @ coef[:, 1], cl


def test_wild_bootstrap_matches_stata_within_monte_carlo_error(data):
    # Stata: t is the cluster-robust t; reps are raised so that 0.025*reps is an integer (999 -> 1000)
    r = run(data, method="twfe", wildBootstrap=True, wbReps=999, ptrends=False, granger=False, grangerPlot=False,
            trendPlots=False, **ATET["A"]["kw"])
    row = r.get_table("wildboot").rows[0]
    assert close(row["t"], 29.12182454735, rel=1e-9) and r.wild["reps"] == 1000 and row["p"] == 0.0
    # Confidence bounds depend on the random weights (Stata's generator differs). Webb weights, Stata
    # rseed(777) reps(9999) -> 10,000: [1.969946289542432, 2.300437287945259]; group(region) rseed(2468) reps(1999)
    # -> 2,000: [2.010375711885763, 2.250656250717449]. Over seeds our bounds vary by about +-0.005 (G=15, B=10,000)
    # and +-0.003 (G=150, B=2,000), so 0.01 (about 6% of the half-width of the interval) is the Monte Carlo tolerance.
    for grp, reps, ref in (("province", 9999, (1.969946289542432, 2.300437287945259)),
                           ("region", 1999, (2.010375711885763, 2.250656250717449))):
        kw = dict(ATET["A"]["kw"], group=grp)
        r = run(data, method="twfe", wildBootstrap=True, wbReps=reps, wbWeight="webb", ptrends=False, granger=False,
                grangerPlot=False, trendPlots=False, **kw)
        row = r.get_table("wildboot").rows[0]
        assert abs(row["lb"] - ref[0]) < 0.01 and abs(row["ub"] - ref[1]) < 0.01
    # all 2^15 Rademacher sign vectors (deterministic) lie close to Stata's Webb result as well
    _, _, Zt, yr, dr, cl = _wb_inputs(data, "province")
    W = np.array(list(itertools.product([-1.0, 1.0], repeat=15))).T[:, 1:]
    full = wild_bootstrap(yr, dr, Zt, cl, W=W)
    assert abs(full["lb"] - 1.969946289542432) < 0.01 and abs(full["ub"] - 2.300437287945259) < 0.01


def test_wild_bootstrap_cluster_algebra_equals_brute_force(data):
    """The cluster-level formulas (Roodman et al. 2019) give the bootstrap t of refitting xtreg, fe on each y*."""
    from pyjamovi.analyses.panel_module import fit_within
    D, Z, Zt, yr, dr, cl = _wb_inputs(data, "province")
    W = np.random.default_rng(5).choice([-1.0, 1.0], size=(15, 4))
    wb = wild_bootstrap(yr, dr, Zt, cl, W=W, return_draws=True)
    fitted_r = D.y - yr                  # restricted model (ATET = 0): fitted values; residuals are yr
    X = np.column_stack([D.d, Z])
    names = ["treat1", "x1"] + [f"t{k}" for k in range(Z.shape[1] - 1)]
    clus = pd.factorize(D.P.df["province"])[0]

    def t_of(yv):
        old = D.P.y
        try:
            D.P.y = yv
            f = fit_within(D.P, X, names, "clustered", clus)
        finally:
            D.P.y = old
        k = f.names.index("treat1")
        return f.b[k] / f.se[k]

    ratio = wb["t"] / t_of(D.y)          # the small-sample factor only rescales every t
    brute = np.array([t_of(fitted_r + yr * W[cl, b]) for b in range(W.shape[1])])
    assert np.allclose(wb["tstar"], brute * ratio, rtol=1e-8, atol=1e-10)


