def test_unbalanced_panel_matches_stata(data):
    """Rows with mod(7*region + year, 13) == 0 removed (did_unbal.do). Units whose adoption year is missing form
    later pseudo-cohorts (Stata derives cohorts from the estimation sample); the post-treatment base period of a cohort
    is its last observed period before g, and the aggregation weights count the cohort units of each 2x2 sample."""
    u = data[(data.region * 7 + data.year) % 13 != 0]
    r = run(u, method="hdid", estimator="ra", dep="y2", covs=["x1", "x2"], treat="treat2", aggTime=True)
    cells = {x["term"]: x for x in r.get_table("attgt").rows}
    for term, (b, se) in {"2019:2019": (.998208325161179, .2261386968075514),
                          "2019:2017": (.6949627673305843, .3947426098408549),
                          "2023:2023": (3.607184763855797, .3167240923716451),
                          "2018:2018": (1.460007171051203, .258425543913032)}.items():
        assert close(cells[term]["b"], b) and close(cells[term]["se"], se), term
    assert cells["2019:2018"]["b"] is None                        # Stata: omitted
    for kind, key, (b, se) in (("overall", "treat2 (1 vs 0)", (2.450947707429861, .1120896910922971)),
                               ("cohort", "2018", (2.048972376414425, .1636295586275531)),
                               ("time", "2019", (1.477866205478002, .2376207448209697)),
                               ("dynamic", "0", (2.232777560218246, .1407903104203964))):
        row = {x["key"]: x for x in r.get_table(f"agg_{kind}").rows}[key]
        assert close(row["b"], b) and close(row["se"], se), kind
    assert close(r.get_table("ptrends").rows[0]["chi2"], 68.81530058189617)
    r = run(u, method="hdid", estimator="aipw", dep="y2", covs=["x1", "x2"], tcovs=["x2"], treat="treat2",
            controlGroup="notyet")
    ov = r.get_table("agg_overall").rows[0]
    assert close(ov["b"], 2.464080440455569) and close(ov["se"], .1129884156763517)
    assert close(r.get_table("ptrends").rows[0]["chi2"], 92.8295348543277)
    r = run(u, method="hdid", estimator="twfe", dep="y2", covs=["x1", "x2"], treat="treat2")
    cells = {x["term"]: x for x in r.get_table("attgt").rows}
    assert close(cells["2019:2019"]["b"], 1.441968397182391) and close(cells["2019:2019"]["se"], .256318696811924)
    assert cells["2023:2023"]["b"] is None                        # single-unit cohort: interactions not identified
    ov = r.get_table("agg_overall").rows[0]
    assert close(ov["b"], 2.562928629644963) and close(ov["se"], .1104768431587718)
    assert r.get_table("ptrends").rows[0]["df1"] == 18
    r = run(u, method="hdid", estimator="twfe", dep="y2", treat="treat2")
    ov = r.get_table("agg_overall").rows[0]
    assert close(ov["b"], 2.812879716883982) and close(ov["se"], .1203160453950518)
    r = run(u, method="twfe", dep="y1", covs=["x1"], treat="treat1", group="province")
    row = r.get_table("atet").rows[0]
    assert close(row["b"], 2.161984666104597) and close(row["se"], .06892420348475292)
    assert "estat ptrends — 계산 불가" in [t.title for t in r.tables]   # Stata: treatment assignment times vary
    r = run(u, method="event", dep="y2", covs=["x1"], treat="treat2")
    rows = {x["term"]: x for x in r.get_table("event").rows}
    assert close(rows["_lead8"]["b"], -1.961422996082502) and close(rows["_lead8"]["se"], .1926830001354591)
