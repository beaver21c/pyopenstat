def test_invalid_inputs_raise_korean_errors(data):
    with pytest.raises(ValueError, match="없는 변수"):
        run(data, method="twfe", dep="y1", treat="nope", group="province")
    with pytest.raises(ValueError, match="0/1"):
        run(data.assign(t3=data.treat1 * 2), method="twfe", dep="y1", treat="t3")
    with pytest.raises(ValueError, match="같은 집단·시점"):
        run(data, method="twfe", dep="y2", treat="treat2", group="province")
    bad = data.copy()
    bad.loc[(bad.region == 1) & (bad.year == 2020), "treat2"] = 0
    with pytest.raises(ValueError, match="0으로 돌아가는"):
        run(bad, method="hdid", dep="y2", treat="treat2")
    # covariate lists the chosen estimator has no equation for are not applied; the first table says so
    r = run(data, method="hdid", estimator="ra", dep="y2", treat="treat2", tcovs=["x2"])
    assert not r.options["tcovs"] and any("적용하지 않은 입력" in n and "x2" in n for n in r.tables[0].notes)
    r = run(data, method="hdid", estimator="ipw", dep="y2", treat="treat2", covs=["x1"])
    assert not r.options["covs"] and any("적용하지 않은 입력" in n and "x1" in n for n in r.tables[0].notes)
    with pytest.raises(ValueError, match="가능"):
        run(data, method="did2s", dep="y2", treat="treat2")
    with pytest.raises(ValueError, match="hc2"):
        run(data, method="twfe", dep="y1", treat="treat1", covType="hc2")


