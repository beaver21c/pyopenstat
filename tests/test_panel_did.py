def _rel_err(a, b):
    return abs(a - b) / max(1.0, abs(b))


@pytest.mark.parametrize("name", list(HDID))
def test_xthdidregress_matches_stata(data, name):
    ref = HDID[name]
    r = run(data, method="hdid", dep="y2", treat="treat2", aggTime=True, **HDID_SPEC[name])
    tol = REL
    cells = {x["term"]: x for x in r.get_table("attgt").rows}
    for term, (b, se) in ref["cells"].items():
        assert _rel_err(cells[term]["b"], b) < tol and abs(cells[term]["se"] - se) / se < tol, term
    if "2018:2015" not in ref["cells"]:
        assert "2018:2015" not in cells           # adaptive base: the first period has no base period
    for kind in ("overall", "cohort", "time", "dynamic"):
        if kind not in ref:
            continue
        rows = {x["key"]: x for x in r.get_table(f"agg_{kind}").rows}
        for key, (b, se) in ref[kind].items():
            k = "treat2 (1 vs 0)" if key == "ATET" else key
            assert _rel_err(rows[k]["b"], b) < tol and abs(rows[k]["se"] - se) / se < tol, (kind, key)
    pt = r.get_table("ptrends").rows[0]
    if "chi2" in ref["pt"]:
        assert _rel_err(pt["chi2"], ref["pt"]["chi2"]) < tol and pt["df"] == ref["pt"]["df"]
    else:
        assert _rel_err(pt["F"], ref["pt"]["F"]) < tol and pt["df1"] == ref["pt"]["df"] and pt["df2"] == ref["pt"]["df_r"]
    stat = r.get_table("attgt").columns[4]["title"]
    assert stat == ("t" if "TWFE" in name else "z")


